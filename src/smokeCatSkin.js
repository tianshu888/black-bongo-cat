// Transparent VP9 WebM interactive clips generated by GB10 MiniMax H3 (Pika H3 Flex 1024x768 -> 512x384 RGBA)
const videoClips = {
  work_typing:    'work_typing.webm',
  work_idle:      'work_idle.webm',
  work_gaze_scan: 'work_gaze_scan.webm',
  work_mouse:     'work_mouse.webm',
  work_pet:       'work_pet.webm'
};

const sleepPoses = ['napLeft', 'napRight', 'napFlat'];
const propsInPose = { boxPeek: 'boxGroup', feedKibble: 'foodBowlGroup', feedCan: 'tunaCanGroup' };
const mirrorable = new Set(['stretch', 'groom', 'bugHunt']);
const widePoses = new Set([...sleepPoses, 'stretch', 'zoomies', 'bugHunt']);

function getPose(behavior, input) {
  switch (behavior.mode) {
    case 'work':
      if (input.isPetting) return 'pet';
      if (input.typingLookTimer > 0) return 'typing';
      return input.rightPaw.mode === 'mouse' ? 'mouse' : 'idle';
    case 'exhausted':
    case 'nap':
      return sleepPoses[behavior.variant] || 'napLeft';
    case 'somersault':
      return behavior.timer >= 20 && behavior.timer < 72 ? 'somersault' : 'bugHunt';
    default:
      return behavior.mode;
  }
}

function getOutline(image) {
  const mask = document.createElement('canvas');
  const ratio = 144 / Math.max(image.naturalWidth, image.naturalHeight);
  const w = mask.width = Math.ceil(image.naturalWidth * ratio);
  const h = mask.height = Math.ceil(image.naturalHeight * ratio);
  const ctx = mask.getContext('2d', { willReadFrequently: true });
  ctx.drawImage(image, 0, 0, w, h);
  const { data } = ctx.getImageData(0, 0, w, h);

  let left = w, right = 0, top = h, bottom = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (data[(y * w + x) * 4 + 3] < 110) continue;
      left = Math.min(x, left);
      right = Math.max(x, right);
      top = Math.min(y, top);
      bottom = Math.max(y, bottom);
    }
  }
  left = Math.max(0, left - 2);
  top = Math.max(0, top - 2);
  right = Math.min(w, right + 3);
  bottom = Math.min(h, bottom + 3);
  if (left >= right || top >= bottom) return null;

  return { image, data, w, h, left, top, right, bottom };
}

function drawOutline(ctx, outline, x, y, width, height) {
  const { image, left, right, top, bottom, w, h } = outline;
  const sx = image.naturalWidth / w;
  const sy = image.naturalHeight / h;
  ctx.drawImage(image, left * sx, top * sy, (right - left) * sx, (bottom - top) * sy, x, y, width, height);
}

export function createSmokeCatSkin(canvas) {
  const ctx = canvas.getContext('2d');
  const outlines = {};
  const videos = {};
  let frame = null;

  // Offscreen hit-test alpha sampler for live video frames
  const hitCanvas = document.createElement('canvas');
  hitCanvas.width = 64;
  hitCanvas.height = 48;
  const hitCtx = hitCanvas.getContext('2d', { willReadFrequently: true });
  let hitAlphaCache = null;
  let hitFrameCount = 0;

  // Interactive H3 video state machine
  const vState = {
    activeKey: null,
    prevKey: null,
    fade: 1.0,
    typingPhase: 'idle',   // 'idle' | 'active' | 'winddown'
    keyCadence: 0,         // smoothed typing speed -> dynamic playbackRate
    lastTypingTimer: 0,
    lastNormX: 0.5,
    gazeActiveTimer: 0,
    scrubTime: 2.5,
    lastScrubApply: 0
  };

  // Preload static fallback / non-desk poses
  for (const [pose, file] of Object.entries(poseFiles)) {
    const image = new Image();
    image.decoding = 'async';
    image.onload = () => { outlines[pose] = getOutline(image); };
    image.src = new URL(`./skins/smoke-cat/${file}.png`, import.meta.url).href;
  }

  // Preload transparent VP9 WebM interactive work clips
  for (const [key, file] of Object.entries(videoClips)) {
    const vid = document.createElement('video');
    vid.muted = true;
    vid.playsInline = true;
    vid.preload = 'auto';
    vid.loop = key !== 'work_typing' && key !== 'work_gaze_scan';
    vid.src = new URL(`./skins/smoke-video/${file}`, import.meta.url).href;
    const entry = { vid, ready: false, duration: 5.0 };
    vid.addEventListener('loadeddata', () => {
      entry.ready = true;
      entry.duration = (vid.duration && isFinite(vid.duration)) ? vid.duration : 5.0;
      if (key === 'work_gaze_scan') {
        vid.pause();
        vid.currentTime = entry.duration * 0.5;
      }
    });
    vid.addEventListener('error', () => { entry.ready = false; });
    vid.load();
    videos[key] = entry;
  }

  function ensurePlaying(entry, rate = 1.0) {
    if (!entry || !entry.ready) return;
    if (Math.abs(entry.vid.playbackRate - rate) > 0.05) {
      entry.vid.playbackRate = Math.max(0.6, Math.min(2.3, rate));
    }
    if (entry.vid.paused) {
      entry.vid.play().catch(() => {});
    }
  }

  function selectWorkVideo(input) {
    const now = performance.now();

    // Detect fresh keystrokes to drive dynamic typing playbackRate
    if (input.typingLookTimer > vState.lastTypingTimer) {
      vState.keyCadence = Math.min(2.2, vState.keyCadence + 0.42);
    }
    vState.lastTypingTimer = input.typingLookTimer;
    vState.keyCadence = Math.max(0, vState.keyCadence - 0.018);

    // Detect horizontal mouse movement for live gaze scrubbing
    const dxNorm = Math.abs((input.normX ?? 0.5) - vState.lastNormX);
    vState.lastNormX = input.normX ?? 0.5;
    if (dxNorm > 0.004) vState.gazeActiveTimer = 110; // ~1.8s gaze tracking hold
    else if (vState.gazeActiveTimer > 0) vState.gazeActiveTimer--;

    // 1. Petting takes top priority
    if (input.isPetting && videos.work_pet?.ready) {
      vState.typingPhase = 'idle';
      ensurePlaying(videos.work_pet, 1.0 + Math.min(0.45, (input.petIntensity || 0) * 0.015));
      return 'work_pet';
    }

    // 2. Typing 3-Phase State Machine (0..0.72s enter -> 0.72..4.05s loop -> 4.05..end return to idle)
    const tv = videos.work_typing;
    if (tv?.ready) {
      const dur = tv.duration;
      const loopStart = Math.min(0.72, dur * 0.14);
      const loopEnd = Math.min(4.05, dur * 0.79);

      if (input.typingLookTimer > 0) {
        if (vState.typingPhase === 'idle') {
          tv.vid.currentTime = 0.08;
        } else if (vState.typingPhase === 'winddown' && tv.vid.currentTime > loopEnd) {
          tv.vid.currentTime = loopStart + 0.15;
        }
        vState.typingPhase = 'active';
        const rate = 1.05 + Math.min(1.15, vState.keyCadence * 0.65);
        ensurePlaying(tv, rate);
        if (tv.vid.currentTime >= loopEnd) {
          tv.vid.currentTime = loopStart;
        }
        return 'work_typing';
      } else if (vState.typingPhase === 'active' || vState.typingPhase === 'winddown') {
        vState.typingPhase = 'winddown';
        if (tv.vid.currentTime < loopEnd) {
          tv.vid.currentTime = loopEnd;
        }
        ensurePlaying(tv, 1.25);
        if (tv.vid.ended || tv.vid.currentTime >= dur - 0.06) {
          vState.typingPhase = 'idle';
          tv.vid.pause();
        } else {
          return 'work_typing';
        }
      }
    }

    // 3. Mouse operating mode (active clicking / mouse work)
    if ((input.mouseLeftDown || input.mouseRightDown || input.rightPaw.mode === 'mouse') && videos.work_mouse?.ready) {
      ensurePlaying(videos.work_mouse, (input.mouseLeftDown || input.mouseRightDown) ? 1.45 : 1.0);
      return 'work_mouse';
    }

    // 4. Live Mouse Gaze Scrubbing (normX 0..1 -> frame 0..end on All-Intra work_gaze_scan.webm!)
    const gv = videos.work_gaze_scan;
    if (vState.gazeActiveTimer > 0 && gv?.ready) {
      if (!gv.vid.paused) gv.vid.pause();
      const targetT = Math.max(0.04, Math.min(0.96, input.normX ?? 0.5)) * gv.duration;
      vState.scrubTime += (targetT - vState.scrubTime) * 0.20;
      if (now - vState.lastScrubApply > 24 && Math.abs(gv.vid.currentTime - vState.scrubTime) > 0.025) {
        gv.vid.currentTime = vState.scrubTime;
        vState.lastScrubApply = now;
      }
      return 'work_gaze_scan';
    }

    // 5. Cozy Idle Breathing & Blinking
    if (videos.work_idle?.ready) {
      ensurePlaying(videos.work_idle, 1.0);
      return 'work_idle';
    }

    return null;
  }

  function draw({ enabled, behavior, input, width, height, dpr, motion }) {
    const pixelWidth = Math.round(width * dpr);
    const pixelHeight = Math.round(height * dpr);
    if (canvas.width !== pixelWidth || canvas.height !== pixelHeight) {
      canvas.width = pixelWidth;
      canvas.height = pixelHeight;
    }

    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, width, height);
    frame = null;
    if (!enabled) return;

    const mode = behavior.mode;
    const atDesk = mode === 'work';
    const unit = Math.min(width / 500, height / 390);

    // --- A. Interactive GB10 Pika H3 Flex Transparent Video Engine (Work Mode) ---
    if (atDesk) {
      const vidKey = selectWorkVideo(input);
      if (vidKey && videos[vidKey]?.ready) {
        if (vState.activeKey !== vidKey) {
          vState.prevKey = vState.activeKey;
          vState.activeKey = vidKey;
          vState.fade = vState.prevKey ? 0.0 : 1.0;
        }
        vState.fade = Math.min(1.0, vState.fade + 0.18);

        // Pause inactive looping videos to save CPU
        for (const [k, entry] of Object.entries(videos)) {
          if (k !== vState.activeKey && k !== vState.prevKey && entry.ready && !entry.vid.paused) {
            entry.vid.pause();
          }
        }

        const drawWidth = 312 * unit;
        const drawHeight = drawWidth * (384 / 512);
        const x = width / 2 + 24 * unit;
        const ground = height / 2 + 124 * unit;
        const clickBounce = (input.mouseLeftDown || input.mouseRightDown) ? 0.992 : 1.0;
        const stretch = clickBounce + (vidKey === 'work_typing' ? input.kbRecoil.y * 0.14 : 0);
        const drawY = ground - (drawHeight * stretch) / 2;

        ctx.save();
        ctx.translate(x, drawY);
        ctx.scale(1, stretch);
        if (vState.fade < 0.99 && vState.prevKey && videos[vState.prevKey]?.ready) {
          ctx.globalAlpha = 1.0 - vState.fade;
          ctx.drawImage(videos[vState.prevKey].vid, -drawWidth / 2, -drawHeight / 2, drawWidth, drawHeight);
        }
        ctx.globalAlpha = vState.fade < 0.99 ? vState.fade : 1.0;
        ctx.drawImage(videos[vidKey].vid, -drawWidth / 2, -drawHeight / 2, drawWidth, drawHeight);
        ctx.restore();

        // Refresh low-res alpha hit-test mask every 6 frames (~10Hz, <0.05ms)
        hitFrameCount++;
        if (hitFrameCount % 6 === 0 || !hitAlphaCache) {
          hitCtx.clearRect(0, 0, 64, 48);
          hitCtx.drawImage(videos[vidKey].vid, 0, 0, 64, 48);
          hitAlphaCache = hitCtx.getImageData(0, 0, 64, 48).data;
        }

        frame = {
          isVideo: true, pose: vidKey, mode, atDesk, x, y: drawY,
          angle: 0, flip: 1, stretch, drawWidth, drawHeight,
          bakedProp: null
        };
        return;
      }
    }

    // --- B. Non-Desk Full-Body Poses (Nap, Stretch, Loaf, Groom, BoxPeek, etc.) ---
    const pose = getPose(behavior, input);
    const outline = outlines[pose] || (atDesk ? outlines.idle : null);
    if (!outline) return;

    const shapeWidth = (outline.right - outline.left) * outline.image.naturalWidth / outline.w;
    const shapeHeight = (outline.bottom - outline.top) * outline.image.naturalHeight / outline.h;
    const maxWidth = (atDesk ? 268 : widePoses.has(pose) ? 286 : 224) * unit;
    const maxHeight = (atDesk ? 222 : widePoses.has(pose) ? 146 : 200) * unit;
    const scale = Math.min(maxWidth / shapeWidth, maxHeight / shapeHeight);
    const drawWidth = shapeWidth * scale;
    const drawHeight = shapeHeight * scale;

    let x = width / 2 + (atDesk ? 34 : 12) * unit;
    let ground = height / 2 + (atDesk ? 112 : 92) * unit;
    let angle = 0;
    let flip = behavior.variant === 1 && mirrorable.has(pose) ? -1 : 1;
    let stretch = 1 + Math.sin(input.breathPhase) * 0.006;

    if (pose === 'zoomies') {
      flip = behavior.zoomDir > 0 ? -1 : 1;
      x += behavior.zoomX * 65 * unit;
      ground -= (11 + Math.abs(Math.sin(behavior.timer * 0.34)) * 16) * unit;
    } else if (pose === 'somersault') {
      const phase = (behavior.timer - 20) / 52;
      ground -= 65 * Math.sin(phase * Math.PI) * unit;
      angle = (phase - 0.5) * Math.PI * 2 * (behavior.variant === 1 ? -1 : 1);
    } else if (mode === 'bugHunt' && behavior.timer >= 150 && !behavior.bugCaught) {
      const leap = Math.sin(Math.min(1, (behavior.timer - 150) / 25) * Math.PI);
      ground -= 52 * leap * unit;
      angle = -0.32 * leap * flip;
    } else if (mode === 'playWand' || mode === 'playYarn' || mode === 'feedChuru') {
      angle = Math.max(-0.12, Math.min(0.12, (motion?.yaw || 0) * 0.15));
      x += Math.max(-20, Math.min(20, (motion?.yaw || 0) * 26)) * unit;
    }

    x = Math.max(drawWidth / 2 + 4 * unit, Math.min(width - drawWidth / 2 - 4 * unit, x));
    const drawY = ground - drawHeight * stretch / 2;
    ctx.save();
    ctx.translate(x, drawY);
    ctx.rotate(angle);
    ctx.scale(flip, stretch);
    drawOutline(ctx, outline, -drawWidth / 2, -drawHeight / 2, drawWidth, drawHeight);
    ctx.restore();

    frame = {
      isVideo: false, pose, mode, atDesk, x, y: drawY,
      angle, flip, stretch, drawWidth, drawHeight, outline,
      bakedProp: propsInPose[mode]
    };
  }

  function hitTest(x, y) {
    if (!frame) return null;
    const { drawWidth, drawHeight, angle, flip, stretch } = frame;
    const dx = x - frame.x, dy = y - frame.y;
    const lx = (dx * Math.cos(angle) + dy * Math.sin(angle)) * flip;
    const ly = (dy * Math.cos(angle) - dx * Math.sin(angle)) / stretch;
    const u = lx / drawWidth + 0.5, v = ly / drawHeight + 0.5;
    if (u < 0 || u >= 1 || v < 0 || v >= 1) return null;

    if (frame.isVideo) {
      if (!hitAlphaCache) return 'cat';
      const px = Math.min(63, Math.max(0, Math.floor(u * 64)));
      const py = Math.min(47, Math.max(0, Math.floor(v * 48)));
      if (hitAlphaCache[(py * 64 + px) * 4 + 3] < 90) return null;
      if (v > 0.85) return 'prop';
      return 'cat';
    }

    const { outline } = frame;
    const px = Math.floor(outline.left + u * (outline.right - outline.left));
    const py = Math.floor(outline.top + v * (outline.bottom - outline.top));
    if (outline.data[(py * outline.w + px) * 4 + 3] < 110) return null;
    if ((frame.atDesk && v > 0.89) || (frame.mode === 'boxPeek' && v > 0.69)) return 'prop';
    return 'cat';
  }

  function drawPortrait(target, pose) {
    const face = pose === 'happy' ? outlines.pet : outlines.portrait;
    if (!face) return false;
    const { image, w, h, left, right, top, bottom } = face;
    const xScale = image.naturalWidth / w;
    const yScale = image.naturalHeight / h;
    const x = left * xScale;
    const y = top * yScale;
    const artWidth = (right - left) * xScale;
    const artHeight = (bottom - top) * yScale;
    const size = Math.min(artWidth * 0.78, artHeight * 0.72, image.naturalHeight - y);
    const center = x + artWidth * (pose === 'happy' ? 0.43 : 0.46);
    target.drawImage(image, Math.max(0, Math.min(image.naturalWidth - size, center - size / 2)), y, size, size, 4, 9, 232, 232);
    return true;
  }

  return { draw, hitTest, drawPortrait, get frame() { return frame; } };
}
